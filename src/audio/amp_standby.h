// Керування входом standby підсилювача (вихідний пін pins::kAmpStby, GPIO46).
// Рівні: «працює» = amp_cfg::kRunLevelHigh (за замовчуванням HIGH), «standby» — протилежний.
// Модуль лише ставить рівень піна: затримки прогріву/вимкнення, мʼют і порядок дій
// координує AppController (core/app_controller.cpp). Нових задач немає, блокувань немає.
//
// [Prompt 23c] Створено. Тіло компілюється лише при FEATURE_AMP_STANDBY == 1
// (config/features.h); при 0 нікому викликати цей клас.

class AmpStandby {
public:
    // Пін -> вихід, одразу рівень standby (без глітчу: рівень защолкується ДО увімкнення
    // виходу). Викликати якомога раніше (перший рядок setup()). Повторний виклик безпечний
    // і знову ставить standby. true — пін налаштовано.
    static bool begin();

    // true — підсилювач працює, false — standby. Негайно, без затримок. Якщо begin() ще не
    // викликався — викликає його. Повторне встановлення того самого стану нічого не робить.
    static void set(bool run);

    // Останній ЗАПИТАНИЙ стан (не вимір піна).
    static bool isRunning();
};
