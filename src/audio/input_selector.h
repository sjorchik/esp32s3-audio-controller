#pragma once

// Реле-селектор зовнішніх входів (TV Box / Computer).
// [Prompt 48a] Створено; замінює TDA7318 / PT2313L (їх вирізано повністю).
//
// ОДНЕ DPDT-реле на ОДНОМУ GPIO (pins::kInputRelay): вимкнено = логічний вхід 1 (TV Box),
// увімкнено = логічний вхід 2 (Computer). Вихід реле йде на вхід PCM1808. Радіо (логічний 0) реле НЕ чіпає
// й стану реле від нього не вимагає.
//
// Модуль НЕБЛОКУЮЧИЙ: select() лише виставляє рівень піна. Паузу після перемикання
// (input_selector_cfg::kRelaySettleMs) і цифровий мʼют line_path на цей час забезпечує ВИКЛИКАЧ
// (AppController: мʼют проходу -> select() -> пауза -> розмʼют). Викликати select() без мʼюту
// проходу не можна: клацання реле потрапило б у динаміки.
//
// Потоки: begin() — з setup(), до старту AppController; select() / current() — лише з задачі
// AppController (під її мʼютексом). Власного мʼютекса модуль не має.
//
// Лог (Serial, префікс [SEL]):
//   begin():   "[SEL] relay pin=<n> activeHigh=<0|1> -> TV Box"
//   select():  "[SEL] input=<n> relay=<on|off>"

#include <stdint.h>

namespace input_selector {

// Налаштовує пін реле як вихід і ставить реле в «вимкнено» (TV Box). Повторний виклик безпечний
// (повертає true, пін не чіпає). Завжди true на ESP32 (GPIO налаштовується без помилок).
bool begin();

// Перемикає реле на логічний вхід: 1 -> TV Box (реле вимкнено), 2 -> Computer (реле увімкнено).
// Для 0 (радіо) і будь-якого іншого значення нічого не робить (false). true — реле виставлено
// (також коли воно вже було в потрібному стані: пін перезаписується тим самим рівнем).
// До begin() нічого не робить (false).
bool select(uint8_t logicalInput);

// Логічний вхід, на який зараз виставлено реле: 1 (TV Box) або 2 (Computer). До begin() — 1.
// Це стан реле, а НЕ поточний вхід пристрою (на радіо реле лишається на останньому зовнішньому вході).
uint8_t current();

}  // namespace input_selector
